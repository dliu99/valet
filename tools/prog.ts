const W = (await import("node:url")).fileURLToPath(new URL("..", import.meta.url)).replace(/\/$/, "");
const { loadEnv, loadConfig } = await import(`${W}/brain/config.ts`);
const { makeDecider } = await import(`${W}/brain/decision.ts`);
const { Recorder, fileSink, recorded } = await import(`${W}/brain/record.ts`);
const { armClient } = await import(`${W}/brain/arm.ts`);
const { runProgram } = await import(`${W}/brain/program.ts`);
const { builtinModels } = await import(`${W}/node_modules/@earendil-works/pi-ai/dist/providers/all.js`);
const { writeFileSync, readFileSync } = await import("node:fs");
process.chdir(W);
(await import("node:fs")).mkdirSync(`${W}/runs/prog`, { recursive: true });
loadEnv();
const config = loadConfig();
const recorder = new Recorder(`${W}/runs/frames`, fileSink(`${W}/runs/prog/prog.jsonl`));
const model = recorded(await makeDecider("jev", { config, models: builtinModels() }), recorder);
const code = readFileSync(process.argv[2]!, "utf8");
const { existsSync } = await import("node:fs");
const SCRATCH = `${W}/runs/prog/scratch.json`;
const scratch = existsSync(SCRATCH) ? JSON.parse(readFileSync(SCRATCH, "utf8")) : {};
const out = await runProgram("manual", code, { arm: armClient(config.armdUrl), model, recorder, view: config.viewpoints.wrist }, new AbortController().signal, Number(process.argv[3] ?? 60), scratch);
writeFileSync(SCRATCH, JSON.stringify(scratch));
for (const line of out.log) console.log(line);
console.log(JSON.stringify({ ok: out.ok, error: out.error, ms: out.ms }));
if (out.frames.wrist) writeFileSync(`${W}/runs/prog/prog.jpg`, Buffer.from(out.frames.wrist.data_b64, "base64"));
